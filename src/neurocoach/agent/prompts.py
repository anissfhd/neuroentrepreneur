def project_block(facts: dict[str, Any]) -> str:
    payload = json.dumps(facts, ensure_ascii=False, indent=1, default=str)
    return f"<donnees_projet>\n{payload}\n</donnees_projet>"


def user_block(text: str) -> str:
    # Neutralise toute tentative de fermer la balise et d'injecter des instructions.
    cleaned = text.replace("<", "&lt;").replace(">", "&gt;")
    return f"<message_utilisateur>\n{cleaned}\n</message_utilisateur>"


